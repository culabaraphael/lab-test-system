import { useEffect, useRef, useState } from "react";
import { useSearchParams } from "react-router-dom";

import { API_URL } from "../../config";
import LifestyleTips from "../../components/LifestyleTips";
import { COPY as LIFESTYLE_COPY } from "../../components/lifestyleCopy";
import { downloadResultPdf, printResultPdf } from "../../utils/resultPdf";

// Drop trailing zeros from numeric strings ("10.0000" -> "10"); leave text alone.
const fmtNum = (v) =>
  v === null || v === undefined || v === "" || Number.isNaN(Number(v))
    ? v
    : String(Number(v));

const AI_COPY = {
  en: {
    title: "Health Information (AI-Generated)",
    disclaimer:
      "This information was generated by AI to help you understand your result. It is not a medical diagnosis or treatment plan. Please consult your doctor or visit your local health office for proper medical advice.",
  },
  ceb: {
    title: "Impormasyon sa Panglawas (Gihimo sa AI)",
    note: "Gihubad sa AI ngadto sa Bisaya. Ang English nga bersyon ang gi-review sa doktor. Kung dili klaro, basaha ang English o pangutana sa imong doktor.",
    disclaimer:
      "Kini nga impormasyon gihimo sa AI aron matabangan ka nga masabtan ang imong resulta. Dili kini medikal nga diagnosis o plano sa pagtambal. Palihug konsultaha ang imong doktor o bisitaha ang imong lokal nga health office para sa saktong medikal nga tambag.",
  },
};

function AiHealthInfo({ rec, token, resultId, onSnapshot }) {
  const [lang, setLang] = useState("en");
  const [ceb, setCeb] = useState(rec?.recommendation_text_ceb || "");
  const [cebLife, setCebLife] = useState(rec?.lifestyle_ceb || null);
  const [translating, setTranslating] = useState(false);
  const [tError, setTError] = useState("");

  // Tell the page what is currently shown (language, text, tips) so that
  // Download PDF produces the same version the patient is reading.
  useEffect(() => {
    if (!onSnapshot) return;

    if (!rec?.recommendation_text) {
      onSnapshot(null);
      return;
    }

    const act = ceb ? lang : "en";
    const cebHasTips =
      !!cebLife &&
      ["food", "routine", "avoid", "notes"].some(
        (k) => (cebLife[k] || []).length > 0
      );
    const useCebTips = act === "ceb" && cebHasTips;
    const copy = LIFESTYLE_COPY[useCebTips ? "ceb" : "en"];

    onSnapshot({
      title: AI_COPY[act].title,
      body: act === "ceb" ? ceb : rec.recommendation_text,
      note: act === "ceb" ? AI_COPY.ceb.note : null,
      disclaimer: AI_COPY[act].disclaimer,
      tips: rec.lifestyle
        ? {
            labels: copy,
            data: useCebTips ? cebLife : rec.lifestyle,
            sources: rec.lifestyle.sources || [],
            englishOnly:
              act === "ceb" && !cebHasTips ? LIFESTYLE_COPY.ceb.englishOnly : null,
          }
        : null,
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [rec, lang, ceb, cebLife]);

  if (!rec?.recommendation_text) {
    return null;
  }

  const active = ceb ? lang : "en";
  const body = active === "ceb" ? ceb : rec.recommendation_text;

  const translate = async () => {
    try {
      setTranslating(true);
      setTError("");

      const response = await fetch(
        `${API_URL}/lab-results/access/${encodeURIComponent(token)}/recommendation/translate` +
          (resultId ? `?result=${encodeURIComponent(resultId)}` : ""),
        { method: "POST", headers: { Accept: "application/json" } }
      );

      const data = await response.json();

      if (!response.ok || !data.recommendation_text_ceb) {
        throw new Error(
          data.message || "Unable to translate right now. Please try again."
        );
      }

      setCeb(data.recommendation_text_ceb);
      setCebLife(data.lifestyle_ceb || null);
      setLang("ceb");
    } catch (err) {
      setTError(err.message || "Unable to translate right now.");
    } finally {
      setTranslating(false);
    }
  };

  const pickBisaya = () => {
    // Tips were added after an older Bisaya text was saved: translate them too.
    if (rec.lifestyle && !cebLife && token) {
      translate();
    } else {
      setLang("ceb");
    }
  };

  return (
    <div className="mt-5 border border-blue-200 bg-blue-50 rounded-xl p-5">
      <div className="flex flex-wrap items-center gap-2 mb-3">
        <svg
          className="w-5 h-5 text-blue-700 flex-shrink-0"
          fill="none"
          stroke="currentColor"
          viewBox="0 0 24 24"
        >
          <path
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth={2}
            d="M9.663 17h4.673M12 3v1m6.364 1.636l-.707.707M21 12h-1M4 12H3m3.343-5.657l-.707-.707m2.828 9.9a5 5 0 117.072 0l-.548.547A3.374 3.374 0 0014 18.469V19a2 2 0 11-4 0v-.531c0-.895-.356-1.754-.988-2.386l-.548-.547z"
          />
        </svg>

        <h4 className="text-sm font-semibold text-blue-900">
          {AI_COPY[active].title}
        </h4>

        <div className="ml-auto print:hidden">
          {ceb ? (
            <div
              className="inline-flex rounded-lg border border-blue-300 overflow-hidden"
              role="group"
              aria-label="Language"
            >
              {[
                ["ceb", "Bisaya"],
                ["en", "English"],
              ].map(([code, label]) => (
                <button
                  key={code}
                  type="button"
                  onClick={() =>
                    code === "ceb" ? pickBisaya() : setLang(code)
                  }
                  disabled={translating}
                  aria-pressed={active === code}
                  className={`px-3 py-1 text-xs font-semibold ${
                    active === code
                      ? "bg-blue-700 text-white"
                      : "bg-white text-blue-800 hover:bg-blue-100"
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          ) : (
            token && (
              <button
                type="button"
                onClick={translate}
                disabled={translating}
                className="px-3 py-1 text-xs font-semibold border border-blue-300 text-blue-800 bg-white rounded-lg hover:bg-blue-100 disabled:opacity-60"
              >
                {translating ? "Translating..." : "Translate to Bisaya"}
              </button>
            )
          )}
        </div>
      </div>

      {translating && (
        <p className="text-xs text-blue-700 mb-2 print:hidden" role="status">
          Translating to Bisaya... this can take up to about 20 seconds.
        </p>
      )}

      {tError && (
        <p className="text-xs text-red-600 mb-2 print:hidden">{tError}</p>
      )}

      <div className="rounded-lg border border-blue-200 bg-white p-4">
        <p className="text-sm text-gray-800 whitespace-pre-line leading-relaxed">
          {body}
        </p>

        {active === "ceb" && (
          <p className="text-xs text-blue-700 mt-3">{AI_COPY.ceb.note}</p>
        )}

        <LifestyleTips
          lifestyle={rec.lifestyle}
          lifestyleCeb={cebLife}
          lang={active}
          className="mt-4"
        />
      </div>

      <div className="mt-4 pt-4 border-t border-blue-200">
        <p className="text-xs text-blue-800 font-medium">
          {AI_COPY[active].disclaimer}
        </p>
      </div>
    </div>
  );
}

export default function PatientDashboard() {
  // The QR code opens /patient/dashboard?token=...
  // Patients do not log in; the short-lived token identifies
  // the single released result (see LabResultController::showByToken).
  const [searchParams] = useSearchParams();
  const token = searchParams.get("token");

  const [patient, setPatient] = useState(null);
  const [results, setResults] = useState([]);

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => {
    if (!token) {
      setPatient(null);
      setResults([]);
      setError("");
      setLoading(false);
      return;
    }

    fetchResultByToken();
  }, [token]);

  const fetchResultByToken = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await fetch(
        `${API_URL}/lab-results/access/${encodeURIComponent(token)}`,
        {
          method: "GET",
          headers: {
            Accept: "application/json",
          },
        }
      );

      let data = null;

      try {
        data = await response.json();
      } catch {
        data = null;
      }

      if (!response.ok || !data?.success) {
        throw new Error(
          data?.message ||
            "Unable to retrieve your laboratory result."
        );
      }

      const labResult = data.lab_result;

      setPatient(labResult?.patient || null);
      // Tests encoded together come back as lab_results (one QR code).
      setResults(
        Array.isArray(data.lab_results) && data.lab_results.length > 0
          ? data.lab_results
          : labResult
          ? [labResult]
          : []
      );
    } catch (err) {
      console.error("Patient Dashboard error:", err);

      setPatient(null);
      setResults([]);

      setError(
        err instanceof TypeError
          ? "Cannot reach the server. Please try again or ask the Counter/Nurse for help."
          : err.message ||
              "Unable to retrieve your laboratory result."
      );
    } finally {
      setLoading(false);
    }
  };

  const aiSnapshots = useRef({});

  const buildPdfRows = (result) =>
    (Array.isArray(result.parameters) ? result.parameters : []).map((p) => {
      const has = (v) => v !== null && v !== undefined && v !== "";
      const low = fmtNum(p.reference_low);
      const high = fmtNum(p.reference_high);
      // One-sided ranges: the system flags HIGH only above the upper limit,
      // so "<= 200" (and ">= x" for a lower limit only).
      const range =
        has(low) && has(high)
          ? `${low} - ${high}`
          : has(high)
          ? `<= ${high}`
          : has(low)
          ? `>= ${low}`
          : "";

      return {
        name: p.parameter_name || "Parameter",
        value: String(fmtNum(p.value_numeric) ?? p.value_text ?? "-"),
        unit: p.unit || "-",
        reference: p.reference_text || range || "-",
        flag: String(p.flag || "UNASSESSED").toUpperCase(),
      };
    });

  const fmtDateTime = (value) =>
    value
      ? new Date(value).toLocaleString([], {
          month: "short",
          day: "numeric",
          year: "numeric",
          hour: "numeric",
          minute: "2-digit",
        })
      : "";

  const ageOn = (dob, when) => {
    if (!dob) return "";
    const b = new Date(dob);
    const d = when ? new Date(when) : new Date();
    if (Number.isNaN(b.getTime())) return "";
    let age = d.getFullYear() - b.getFullYear();
    const m = d.getMonth() - b.getMonth();
    if (m < 0 || (m === 0 && d.getDate() < b.getDate())) age--;
    return age >= 0 ? String(age) : "";
  };

  // Data for the printed / downloaded copy (same layout for both), in the
  // language the patient is currently reading.
  const buildPdfData = (result) => ({
    patientName: getPatientName(),
    patientId: patient?.patient_id || "",
    birthday: patient?.date_of_birth ? String(patient.date_of_birth).slice(0, 10) : "",
    age: ageOn(patient?.date_of_birth, result.approved_at),
    sex: patient?.sex || "",
    encodedAt: fmtDateTime(result.submitted_at || result.created_at),
    releasedAt: fmtDateTime(result.approved_at),
    examinedBy: result.encoder?.name || "",
    approvedBy: result.reviewer?.name || "",
    testName: getTestName(result),
    date: getDate(result),
    rows: buildPdfRows(result),
    ai: aiSnapshots.current[result.id] || null,
  });

  // Download PDF: builds a real PDF file in the browser (no extra library).
  const handleDownloadPdf = (result) => {
    downloadResultPdf(buildPdfData(result));
  };

  // Print = the same PDF as Download, sent to the print dialog, so the
  // printed copy has the hospital layout. (The old page-print code below is
  // kept as handlePagePrint but no longer used by the button.)
  const handlePrint = (result) => {
    printResultPdf(buildPdfData(result));
  };

  // eslint-disable-next-line no-unused-vars
  const handlePagePrint = () => {
    const previousTitle = document.title;
    const safeId = String(patient?.patient_id || "result").replace(
      /[^A-Za-z0-9_-]/g,
      ""
    );
    const day = new Date().toISOString().slice(0, 10);
    document.title = `Lab-Result-${safeId}-${day}`;

    const restore = () => {
      document.title = previousTitle;
      window.removeEventListener("afterprint", restore);
    };
    window.addEventListener("afterprint", restore);

    window.print();
  };

  const getPatientName = () => {
    if (!patient) return "";

    return `${patient.first_name || ""} ${
      patient.middle_name
        ? `${patient.middle_name} `
        : ""
    }${patient.last_name || ""}`.trim();
  };

  const getTestName = (result) => {
    return (
      result.test_type?.name ||
      result.testType?.name ||
      result.test_type?.test_name ||
      result.testType?.test_name ||
      "Laboratory Test"
    );
  };

  const getDate = (result) => {
    const date =
      result.approved_at ||
      result.submitted_at ||
      result.created_at;

    if (!date) return "Date unavailable";

    return new Date(date).toLocaleDateString();
  };

  return (
    <div className="min-h-screen bg-gray-50">

      {/* Header */}
      <header className="bg-white border-b border-gray-200 print:hidden">
        <div className="max-w-5xl mx-auto px-4 sm:px-6 py-4 flex items-center justify-between">

          <div>
            <h1 className="text-xl font-bold text-gray-900">
              Lab Result System
            </h1>

            <p className="text-sm text-gray-500">
              Patient Portal
            </p>
          </div>

      

        </div>
      </header>

      {/* Main */}
      <main className="max-w-5xl mx-auto px-3 sm:px-6 py-6 sm:py-10 print:px-0 print:py-0">

        {/* Print-only heading (not shown on screen) */}
        <div className="hidden print:block mb-6 pb-3 border-b border-gray-400">
          <p className="text-lg font-bold text-gray-900">
            Esperanza MediCare Community Hospital
          </p>
          <p className="text-sm text-gray-700">
            Laboratory Result (Patient Copy)
          </p>
          <p className="text-xs text-gray-600 mt-1">
            Printed on {new Date().toLocaleString()}
          </p>
        </div>

        <div className="mb-8">
          <h2 className="text-2xl font-bold text-gray-900">
            Laboratory Result
          </h2>

          <p className="text-gray-600 mt-1">
            View your released laboratory test result.
          </p>
        </div>

        {/* Loading */}
        {loading && (
          <section className="bg-white rounded-xl border border-gray-200 shadow-sm p-12 text-center">

            <div className="mx-auto w-10 h-10 border-4 border-gray-200 border-t-gray-700 rounded-full animate-spin mb-4" />

            <p className="text-gray-500">
              Loading laboratory result...
            </p>

          </section>
        )}

        {/* Error */}
        {!loading && error && (
          <section className="bg-white rounded-xl border border-red-200 shadow-sm p-8">

            <div className="bg-red-50 rounded-lg p-5 text-center">

              <h3 className="font-semibold text-red-800">
                Result Not Available
              </h3>

              <p className="text-sm text-red-600 mt-1">
                {error}
              </p>

            </div>

          </section>
        )}

        {/* Empty */}
        {!loading && !error && !token && (
          <section className="bg-white rounded-xl border border-gray-200 shadow-sm p-10">

            <div className="border border-dashed border-gray-300 rounded-xl py-14 text-center">

              <div className="mx-auto w-16 h-16 rounded-full bg-gray-100 flex items-center justify-center mb-5">

                <svg
                  className="w-8 h-8 text-gray-400"
                  fill="none"
                  stroke="currentColor"
                  viewBox="0 0 24 24"
                >
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    strokeWidth={2}
                    d="M9 12h6m-6 4h6m2 5H7a2 2 0 01-2-2V5a2 2 0 012-2h6l5 5v11a2 2 0 01-2 2z"
                  />
                </svg>

              </div>

              <h3 className="text-lg font-semibold text-gray-900">
                No Laboratory Result
              </h3>

              <p className="text-sm text-gray-500 mt-2 max-w-md mx-auto">
                Scan the QR code provided by the laboratory
                to access your released laboratory result.
              </p>

            </div>

          </section>
        )}

        {/* Patient + Results */}
        {!loading && !error && patient && (
          <div className="space-y-6">

            {/* Patient Information */}
            <section className="bg-white rounded-xl border border-gray-200 shadow-sm p-4 sm:p-6">

              <h3 className="text-lg font-semibold text-gray-900 mb-5">
                Patient Information
              </h3>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-5">

                <div>
                  <p className="text-xs text-gray-500 uppercase">
                    Patient Name
                  </p>

                  <p className="font-medium text-gray-900 mt-1">
                    {getPatientName()}
                  </p>
                </div>

                <div>
                  <p className="text-xs text-gray-500 uppercase">
                    Patient ID
                  </p>

                  <p className="font-medium text-gray-900 mt-1">
                    {patient.patient_id}
                  </p>
                </div>

              </div>

            </section>

            {/* Laboratory Results */}
            <section className="bg-white rounded-xl border border-gray-200 shadow-sm p-4 sm:p-6">

              <div className="mb-5">

                <h3 className="text-lg font-semibold text-gray-900">
                  Laboratory Result
                </h3>

                <p className="text-sm text-gray-500 mt-1">
                  Your laboratory test result.
                </p>

              </div>

              {results.length === 0 ? (

                <div className="border border-dashed border-gray-300 rounded-xl py-12 text-center">

                  <h4 className="font-semibold text-gray-900">
                    No Laboratory Result
                  </h4>

                  <p className="text-sm text-gray-500 mt-1">
                    No laboratory result has been recorded
                    for this patient.
                  </p>

                </div>

              ) : (

                <div className="space-y-5">

                  {results.map((result) => (

                    <div
                      key={result.id}
                      className="border border-gray-200 rounded-xl p-3 sm:p-5"
                    >

                      {/* Test Header */}
                      <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-3 mb-5">

                        <div>

                          <h4 className="text-lg font-semibold text-gray-900">
                            {getTestName(result)}
                          </h4>

                          <p className="text-sm text-gray-500 mt-1">
                            Date: {getDate(result)}
                          </p>

                        </div>

                        <div className="flex flex-wrap items-center gap-2 sm:gap-3">
                          <span className="px-3 py-1 rounded-full bg-green-100 text-green-700 text-xs font-semibold w-fit">
                            {String(result.status || "UNKNOWN").replaceAll(
                              "_",
                              " "
                            )}
                          </span>

                          <button
                            type="button"
                            onClick={() => handlePrint(result)}
                            className="print:hidden inline-flex items-center gap-2 px-3 py-1.5 text-xs font-semibold border border-gray-300 text-gray-800 rounded-lg hover:bg-gray-100"
                          >
                            <svg
                              className="w-4 h-4"
                              fill="none"
                              stroke="currentColor"
                              viewBox="0 0 24 24"
                            >
                              <path
                                strokeLinecap="round"
                                strokeLinejoin="round"
                                strokeWidth={2}
                                d="M6 9V3h12v6M6 18H4a2 2 0 01-2-2v-5a2 2 0 012-2h16a2 2 0 012 2v5a2 2 0 01-2 2h-2M6 14h12v7H6v-7z"
                              />
                            </svg>
                            Print
                          </button>

                          <button
                            type="button"
                            onClick={() => handleDownloadPdf(result)}
                            className="print:hidden inline-flex items-center gap-2 px-3 py-1.5 text-xs font-semibold border border-gray-300 text-gray-800 rounded-lg hover:bg-gray-100"
                          >
                            <svg
                              className="w-4 h-4"
                              fill="none"
                              stroke="currentColor"
                              viewBox="0 0 24 24"
                            >
                              <path
                                strokeLinecap="round"
                                strokeLinejoin="round"
                                strokeWidth={2}
                                d="M4 16v2a2 2 0 002 2h12a2 2 0 002-2v-2M12 4v12m0 0l-4-4m4 4l4-4"
                              />
                            </svg>
                            Download PDF
                          </button>
                        </div>

                      </div>

                      {/* Parameters */}
                      {Array.isArray(result.parameters) &&
                      result.parameters.length > 0 ? (

                        <div className="overflow-x-auto">

                          <table className="w-full text-xs sm:text-sm">

                            <thead>

                              <tr className="border-b border-gray-200 text-left">

                                <th className="py-3 pr-2 sm:pr-4 font-semibold text-gray-700">
                                  Parameter
                                </th>

                                <th className="py-3 pr-2 sm:pr-4 font-semibold text-gray-700">
                                  Result
                                </th>

                                <th className="hidden sm:table-cell py-3 pr-4 font-semibold text-gray-700">
                                  Unit
                                </th>

                                <th className="py-3 pr-2 sm:pr-4 font-semibold text-gray-700">
                                  Reference
                                </th>

                                <th className="py-3 font-semibold text-gray-700">
                                  Status
                                </th>

                              </tr>

                            </thead>

                            <tbody>

                              {result.parameters.map(
                                (parameter) => (

                                  <tr
                                    key={parameter.id}
                                    className="border-b border-gray-100"
                                  >

                                    <td className="py-3 sm:py-4 pr-2 sm:pr-4 text-gray-900">
                                      {parameter.parameter_name ||
                                        "Parameter"}
                                    </td>

                                    <td className="py-3 sm:py-4 pr-2 sm:pr-4 font-medium text-gray-900">
                                      {fmtNum(parameter.value_numeric) ??
                                        parameter.value_text ??
                                        "—"}
                                      {parameter.unit && (
                                        <span className="sm:hidden font-normal text-gray-500">
                                          {" "}{parameter.unit}
                                        </span>
                                      )}
                                    </td>

                                    <td className="hidden sm:table-cell py-4 pr-4 text-gray-600">
                                      {parameter.unit || "—"}
                                    </td>

                                    <td className="py-3 sm:py-4 pr-2 sm:pr-4 text-gray-600">

                                      {parameter.reference_text ||
                                      parameter.reference_low !==
                                        null ||
                                      parameter.reference_high !==
                                        null
                                        ? parameter.reference_text ||
                                          `${fmtNum(parameter.reference_low) ?? ""}${
                                            parameter.reference_low !==
                                              null &&
                                            parameter.reference_high !==
                                              null
                                              ? " – "
                                              : ""
                                          }${
                                            fmtNum(parameter.reference_high) ??
                                            ""
                                          }`
                                        : "—"}

                                    </td>

                                    <td className="py-4">
                                      {(() => {
                                        const flag = String(
                                          parameter.flag || "UNASSESSED"
                                        ).toUpperCase();

                                        const styles = {
                                          NORMAL: "bg-green-100 text-green-700",
                                          HIGH: "bg-red-100 text-red-700",
                                          ABNORMAL: "bg-red-100 text-red-700",
                                          LOW: "bg-orange-100 text-orange-700",
                                        };

                                        if (!styles[flag]) {
                                          return (
                                            <span className="text-gray-400">
                                              —
                                            </span>
                                          );
                                        }

                                        return (
                                          <span
                                            className={`inline-flex px-2.5 py-1 rounded-full text-xs font-semibold ${styles[flag]}`}
                                          >
                                            {flag}
                                          </span>
                                        );
                                      })()}
                                    </td>

                                  </tr>

                                )
                              )}

                            </tbody>

                          </table>

                        </div>

                      ) : (

                        <div className="border border-dashed border-gray-300 rounded-lg p-8 text-center">

                          <p className="text-sm text-gray-500">
                            No parameter results are available.
                          </p>

                        </div>

                      )}

                      {/* All-normal notice (Figure 3-9: no LLM call when nothing is abnormal) */}
                      {Array.isArray(result.parameters) &&
                        result.parameters.length > 0 &&
                        result.parameters.every(
                          (p) =>
                            String(p.flag || "").toUpperCase() === "NORMAL"
                        ) && (
                          <div className="mt-5 border border-green-200 bg-green-50 rounded-xl p-5">
                            <p className="text-sm text-green-800 font-medium">
                              All of your results are within the normal range.
                            </p>
                            <p className="text-xs text-green-700 mt-1">
                              If you have questions about your result, please
                              consult your doctor.
                            </p>
                          </div>
                        )}

                      {/* Print-only disclaimer, always included in the downloaded copy */}
                      <p className="hidden print:block mt-5 text-xs text-gray-700 border-t border-gray-300 pt-3">
                        This printout is a copy of a result released by the
                        laboratory. It is not a medical diagnosis or treatment
                        plan. Please consult your doctor for proper medical
                        advice.
                      </p>

                      {/* AI Health Recommendation (English / Bisaya) */}
                      <AiHealthInfo
                        rec={result.ai_recommendation}
                        token={token}
                        resultId={result.id}
                        onSnapshot={(snap) => {
                          aiSnapshots.current[result.id] = snap;
                        }}
                      />

                    </div>

                  ))}

                </div>

              )}

            </section>

          </div>
        )}

      </main>
    </div>
  );
}