<?php

use App\Http\Controllers\AuthController;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Route;
use App\Http\Controllers\PatientController;
use App\Http\Controllers\TestTypeController;
use App\Http\Controllers\ReferenceRangeController;
use App\Http\Controllers\LabResultController;


Route::post('/login', [AuthController::class, 'login']);

// -----------------------------------------------------------------------
// Public, reference-data-only endpoints (test types / reference ranges).
// No patient-identifiable information here, so these stay open.
// -----------------------------------------------------------------------
Route::get('/test-types', [TestTypeController::class, 'index']);
Route::get('/test-types/{testType}', [TestTypeController::class, 'show']);
Route::get('/test-types/{testType}/parameters', [ReferenceRangeController::class, 'index']);

// -----------------------------------------------------------------------
// Public, token-scoped patient result access (QR code flow, Phase B).
//
// The token is a random, unguessable, 15-minute-expiring credential
// generated by LabResultController::approve() when a Doctor approves a
// result, and re-issuable by the Counter/Nurse via
// LabResultController::regenerateAccessToken(). This endpoint returns
// ONLY the single result matching the token, never the full
// patients/lab-results tables, so a patient needs no login and never
// sees any other patient's data.
// -----------------------------------------------------------------------
Route::get('/lab-results/access/{token}', [LabResultController::class, 'showByToken']);

Route::middleware('auth:sanctum')->group(function () {
    Route::post('/logout', [AuthController::class, 'logout']);

    Route::get('/user', function (Request $request) {
        return response()->json([
            'user' => $request->user(),
        ]);
    });

    // Staff-only: full patient / lab-result listings and single-result
    // detail views (used by MedTech, Doctor, Counter/Nurse dashboards).
    // These used to be wide open with no auth check at all; now any
    // logged-in staff account can read them, but a Patient (who never
    // logs in — see the QR flow above) cannot reach them.
    Route::get('/patients', [PatientController::class, 'index']);
    Route::get('/lab-results', [LabResultController::class, 'index']);
    Route::get('/lab-results/{labResult}', [LabResultController::class, 'show']);

    // Medical Technologist actions: manage patient records and encode/edit
    // laboratory results.
    Route::middleware('role:Medical Technologist')->group(function () {
        Route::post('/patients', [PatientController::class, 'store']);
        Route::put('/patients/{patient}', [PatientController::class, 'update']);
        Route::delete('/patients/{patient}', [PatientController::class, 'destroy']);

        Route::post('/lab-results', [LabResultController::class, 'store']);
        Route::put('/lab-results/{labResult}', [LabResultController::class, 'update']);
        Route::post('/lab-results/{labResult}/cancel', [LabResultController::class, 'cancel']);
    });

    // Doctor actions: approve or reject a pending laboratory result.
    Route::middleware('role:Doctor')->group(function () {
        Route::post('/lab-results/{labResult}/approve', [LabResultController::class, 'approve']);
        Route::post('/lab-results/{labResult}/reject', [LabResultController::class, 'reject']);
        Route::post('/lab-results/{labResult}/recommendation/preview', [LabResultController::class, 'previewRecommendation']);
        Route::put('/lab-results/{labResult}/recommendation', [LabResultController::class, 'updateRecommendation']);
    });

    // Counter/Nurse actions: patient check-in and QR-based result release.
    Route::middleware('role:COUNTER')->group(function () {
        Route::post('/lab-results/{labResult}/qr-token', [LabResultController::class, 'regenerateAccessToken']);
    });
});
